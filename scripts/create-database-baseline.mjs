import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'

const root = process.cwd()
const serverRoot = path.join(root, 'apps/server')
const migrationsRoot = path.join(serverRoot, 'prisma/migrations')
const supplementPath = path.join(serverRoot, 'prisma/bootstrap/supplement.sql')
const epoch = process.argv.find(argument => argument.startsWith('--epoch='))?.slice('--epoch='.length)
const productionSignature = process.argv.find(argument => argument.startsWith('--production-signature='))?.slice('--production-signature='.length)

if (!epoch || !/^\d{8}_[a-z0-9_]+$/.test(epoch)) {
  throw new Error('Use --epoch=YYYYMMDD_name with lowercase letters, digits and underscores')
}
if (!productionSignature || !/^[a-f0-9]{64}$/.test(productionSignature)) {
  throw new Error('Use --production-signature=<64-character lowercase SHA-256> from the verified production-clone schema')
}

const outputDirectory = path.join(serverRoot, 'prisma/baselines', epoch)
const snapshotPath = path.join(outputDirectory, 'schema.sql')
const manifestPath = path.join(outputDirectory, 'manifest.json')
if (fs.existsSync(snapshotPath) || fs.existsSync(manifestPath)) {
  throw new Error(`Baseline ${epoch} already exists; immutable baselines are not overwritten`)
}

const canonicalText = value => String(value).replace(/\r\n?/g, '\n')
const sha256Text = value => crypto.createHash('sha256').update(canonicalText(value), 'utf8').digest('hex')
const migrations = fs.readdirSync(migrationsRoot, { withFileTypes: true })
  .filter(entry => entry.isDirectory() && /^[A-Za-z0-9_]+$/.test(entry.name))
  .map(entry => ({ name: entry.name, file: path.join(migrationsRoot, entry.name, 'migration.sql') }))
  .filter(entry => fs.existsSync(entry.file))
  .sort((left, right) => left.name.localeCompare(right.name))
  .map(entry => ({ name: entry.name, checksum: sha256Text(fs.readFileSync(entry.file, 'utf8')) }))

if (!migrations.length) throw new Error('No Prisma migrations found')
const prismaArguments = [
  'exec', 'prisma', 'migrate', 'diff', '--from-empty',
  '--to-schema-datamodel', 'prisma/schema.prisma', '--script',
]
const generated = spawnSync(
  process.platform === 'win32' ? process.env.ComSpec : 'pnpm',
  process.platform === 'win32'
    ? ['/d', '/s', '/c', `pnpm ${prismaArguments.join(' ')}`]
    : prismaArguments,
  {
  cwd: serverRoot,
  encoding: 'utf8',
  maxBuffer: 32 * 1024 * 1024,
  },
)
if (generated.status !== 0) {
  const detail = `${generated.error?.message || ''}\n${generated.stderr || ''}\n${generated.stdout || ''}`.trim().slice(-4000)
  throw new Error(`Unable to generate Prisma baseline SQL: ${detail}`)
}
if (!generated.stdout.includes('CREATE TABLE')) throw new Error('Generated baseline SQL is unexpectedly empty')

const generatedSchemaSql = canonicalText(generated.stdout)
const supplement = canonicalText(fs.readFileSync(supplementPath, 'utf8'))
const snapshot = [
  `-- Immutable oi-manager database baseline epoch: ${epoch}`,
  '-- Generated from Prisma Schema plus the frozen non-Prisma invariant supplement.',
  '-- Do not edit this file; create a later migration or a new audited epoch.',
  '',
  generatedSchemaSql.trimEnd(),
  '',
  supplement.trimEnd(),
  '',
].join('\n')
const manifest = {
  schemaVersion: 1,
  epoch,
  createdOn: new Date().toISOString().slice(0, 10),
  latestMigration: migrations.at(-1).name,
  migrationCount: migrations.length,
  migrations,
  prismaSchemaSha256: sha256Text(fs.readFileSync(path.join(serverRoot, 'prisma/schema.prisma'), 'utf8')),
  generatedSchemaSqlSha256: sha256Text(generatedSchemaSql),
  supplementSha256: sha256Text(supplement),
  snapshotSha256: sha256Text(snapshot),
  productionSchemaSignatureSha256: productionSignature,
}

fs.mkdirSync(outputDirectory, { recursive: true })
fs.writeFileSync(snapshotPath, snapshot, { encoding: 'utf8' })
fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, { encoding: 'utf8' })
console.log(JSON.stringify({ epoch, migrations: migrations.length, snapshotSha256: manifest.snapshotSha256 }, null, 2))
